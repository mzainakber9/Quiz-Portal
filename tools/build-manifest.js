// =========================================================
// Rebuilds js/manifest.js from everything in /data.
//
//   Run from the project folder:   node tools/build-manifest.js
//
// Use it after adding, renaming or removing a data file. It
// reads each file's class / subject / type / id / label / order
// and writes the list the portal uses to build its dropdowns.
// (No Node? You can also add one line to js/manifest.js by hand
//  — see the README.)
// =========================================================
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const DATA = path.join(ROOT, "data");
const SUBJECT_ORDER = ["Math", "Physics", "Chemistry", "Biology",
                       "Computer", "Islamiyat", "PakStudy", "English"];
const CLASS_ORDER = ["9th", "10th", "11th", "12th"];

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(f =>
    f.isDirectory() ? walk(path.join(dir, f.name)) : [path.join(dir, f.name)]);
}

const entries = [];
let problems = 0;

walk(DATA)
  .filter(f => f.endsWith(".js") && !path.basename(f).startsWith("TEMPLATE"))
  .forEach(file => {
    const rel = path.relative(ROOT, file).split(path.sep).join("/");
    const found = [];
    global.QuizBank = { register: e => found.push(e) };
    try {
      new Function(fs.readFileSync(file, "utf8"))();
    } catch (err) {
      console.error("!! " + rel + " failed to load: " + err.message);
      problems++;
      return;
    }
    if (found.length !== 1) {
      console.error("!! " + rel + " registers " + found.length + " quizzes (expected 1)");
      problems++;
      return;
    }
    const e = found[0];
    entries.push({
      class: e.class, subject: e.subject, type: e.type || "chapter",
      id: e.id, label: e.label, order: e.order || 0, file: rel
    });
  });

const rank = (list, v) => { const i = list.indexOf(v); return i === -1 ? list.length : i; };
entries.sort((a, b) =>
  rank(CLASS_ORDER, a.class) - rank(CLASS_ORDER, b.class) ||
  rank(SUBJECT_ORDER, a.subject) - rank(SUBJECT_ORDER, b.subject) ||
  a.order - b.order || a.id.localeCompare(b.id, undefined, { numeric: true }));

const seen = new Set();
entries.forEach(e => {
  const k = e.class + "|" + e.subject + "|" + e.id;
  if (seen.has(k)) { console.error("!! duplicate id: " + k); problems++; }
  seen.add(k);
});

const lines = entries.map(e => "  " + JSON.stringify(e));
const out =
`// =========================================================
// QUIZ MANIFEST — generated by tools/build-manifest.js
// ---------------------------------------------------------
// One line per chapter / paper. The question files themselves
// are NOT loaded until a student starts that chapter / paper.
// To add content: add the data file, then re-run
//   node tools/build-manifest.js
// or add one line here by hand (copy a neighbouring line; "file"
// is the path to your data file).
// =========================================================
QuizBank.declare([
${lines.join(",\n")}
]);
`;
fs.writeFileSync(path.join(ROOT, "js", "manifest.js"), out);
console.log("js/manifest.js written: " + entries.length + " quizzes" +
            (problems ? " (" + problems + " problem(s) — see above)" : ""));
process.exit(problems ? 1 : 0);
