def distractors(i, field):
    g = ID[i][2]; seen_groups, out, k = {g}, [], 0
    while len(out) < 3:
        j = (i * 7 + k * 5 + 3) % len(ID); k += 1
        if j == i or ID[j][2] in seen_groups: continue
        seen_groups.add(ID[j][2]); out.append(ID[j][field])
    return out

