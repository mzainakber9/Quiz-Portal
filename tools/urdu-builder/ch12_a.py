REL = [("آنکھ","کان"),("ہاتھ","پاؤں"),("شیر","ہاتھی"),("قلم","کتاب"),("دریا","پہاڑ"),("پھول","پتا"),("بادل","بارش"),("آگ","دھواں"),("دودھ","چائے"),("ٹوپی","جوتا"),("کھیت","کسان")]
def fmt(p): return "%s، %s" % p
def free(c, p): return not (set(c) & set(p))
F2 = ["درج ذیل میں سے کون سی جوڑی مترادف الفاظ کی ہے؟","مترادف الفاظ کی جوڑی منتخب کیجیے:","کون سی جوڑی ہم معنی الفاظ پر مشتمل ہے؟","کس جوڑی کے الفاظ کا مطلب ایک جیسا ہے؟","ان جوڑیوں میں سے مترادف جوڑی کون سی ہے؟"]
T2 = []
for i, p in enumerate(CORR):
    wrong = []
    for pool, off in ((ANTW, i), (REL, i * 2), (REL, i * 2 + 5)):
        k = 0
        while True:
            c = pool[(off + k) % len(pool)]; k += 1
            if c not in wrong and free(c, p): wrong.append(c); break
    T2.append(("U", F2[i % 5], fmt(p), *[fmt(w) for w in wrong],
        "‘%s’ اور ‘%s’ کا مطلب ایک جیسا ہے، اس لیے یہ مترادف جوڑی ہے؛ باقی جوڑیوں میں متضاد یا صرف متعلق الفاظ ہیں۔" % p))

NOT = [("دن","رات"),("سچ","جھوٹ"),("اونچا","نیچا"),("امیر","غریب"),("گرم","ٹھنڈا"),("خوشی","غم")]
F3 = ["کون سی جوڑی مترادف الفاظ کی نہیں ہے؟","درج ذیل میں سے کون سی جوڑی ہم معنی نہیں ہے؟"]
T3 = []
for i, p in enumerate(NOT):
    d = []; k = 0
    while len(d) < 3:
        c = CORR[(i * 4 + k * 3) % len(CORR)]; k += 1
        if c not in d and free(c, p): d.append(c)
    T3.append(("U", F3[i % 2], fmt(p), *[fmt(x) for x in d],
        "‘%s’ اور ‘%s’ ہم معنی نہیں بلکہ ایک دوسرے کی ضد ہیں؛ باقی تینوں جوڑیاں ہم معنی ہیں۔" % p))
ITEMS = T1 + T2 + T3
