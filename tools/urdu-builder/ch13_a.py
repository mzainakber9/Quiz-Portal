# Ch13 متلازم الفاظ (no E-code in the framework) - pairs that normally appear together
P = [  # (first, second, category)
("دال","روٹی","food"),("نمک","مرچ","food"),("ساس","بہو","family"),("ماں","باپ","family"),("بھائی","بہن","family"),("میاں","بیوی","family"),
("چور","سپاہی","law"),("تاج","تخت","royal"),("قلم","دوات","writing"),("تیر","کمان","weapon"),("سوئی","دھاگا","sewing"),("ہل","بیل","farm"),
("چولہا","ہانڈی","kitchen"),("چراغ","تیل","light"),("ڈھول","تاشہ","music"),("جوتا","موزہ","wear"),("چاند","ستارے","sky"),("گل","بلبل","garden"),
("شمع","پروانہ","moth"),("بادل","بجلی","weather"),("سورج","دھوپ","sun"),("آگ","دھواں","fire"),("سونا","چاندی","metal"),("آب","دانہ","living"),
("کھانا","پینا","eat"),("لین","دین","trade"),("کھیل","کود","play"),("ہاتھ","پاؤں","body"),
]
def distract(i, field=1):
    out, k, cats = [], 0, {P[i][2]}
    while len(out) < 3:
        j = (i * 5 + k * 7 + 3) % len(P); k += 1
        if P[j][2] in cats: continue
        cats.add(P[j][2]); out.append(P[j][field])
    return out
F1 = ["‘%s’ کا متلازم لفظ ہے:","‘%s’ کے ساتھ عموماً بولا جانے والا لفظ ہے:","لفظ ‘%s’ کا متلازم منتخب کیجیے:"]
T1 = []
for i, (x, y, c) in enumerate(P):
    T1.append(("K" if i < 16 else "U", F1[i % 3] % x, y, *distract(i),
        "‘%s’ اور ‘%s’ عموماً ایک ساتھ بولے جاتے ہیں اور ایک کا ذکر دوسرے کی یاد دلاتا ہے، اس لیے یہ متلازم ہیں۔" % (x, y)))

HOLD = [("دودھ","دہی"),("دلہا","دلہن"),("بادشاہ","وزیر"),("ڈاکٹر","دوا"),("مریض","طبیب"),("مہندی","چوڑیاں"),("کتاب","قلم"),("آب","ہوا"),("لکھنا","پڑھنا"),("سیر","سپاٹا")]
SYN = [("خوشی","مسرت"),("غم","رنج"),("آنکھ","چشم"),("بہادر","دلیر"),("گھر","مکان"),("ڈر","خوف"),("راستہ","راہ"),("پانی","آب")]
ANT = [("اونچا","نیچا"),("سچ","جھوٹ"),("گرم","ٹھنڈا"),("امیر","غریب"),("اندھیرا","اجالا"),("نیا","پرانا")]
def fmt(p): return "%s، %s" % p
F2 = ["کون سی جوڑی متلازم الفاظ کی ہے؟","درج ذیل میں سے متلازم الفاظ کی جوڑی منتخب کیجیے:","کس جوڑی کے الفاظ عموماً ایک ساتھ بولے جاتے ہیں؟"]
T2 = []
for i, p in enumerate(HOLD):
    wrong = [SYN[i % len(SYN)], ANT[i % len(ANT)], SYN[(i + 3) % len(SYN)]]
    wrong = [w for k, w in enumerate(wrong) if w not in wrong[:k]]
    k = 1
    while len(wrong) < 3:
        c = ANT[(i + k) % len(ANT)]; k += 1
        if c not in wrong: wrong.append(c)
    T2.append(("U", F2[i % 3], fmt(p), *[fmt(w) for w in wrong[:3]],
        "‘%s’ اور ‘%s’ عموماً ایک ساتھ بولے جاتے ہیں، اس لیے متلازم ہیں؛ باقی جوڑیاں ہم معنی یا متضاد الفاظ کی ہیں۔" % p))

KINDS = ["متلازم","متضاد","مترادف","مرکبِ اضافی"]
CL = [("نوک","جھونک","متلازم"),("پان","سپاری","متلازم"),("تسبیح","مصلیٰ","متلازم"),("تالا","چابی","متلازم"),("صابن","تولیہ","متلازم"),("چائے","پیالی","متلازم"),
      ("سچ","جھوٹ","متضاد"),("اونچا","نیچا","متضاد"),("گھر","مکان","مترادف"),("ڈر","خوف","مترادف"),("خوشی","مسرت","مترادف"),("گرم","ٹھنڈا","متضاد")]
WHY = {"متلازم":"عموماً ایک ساتھ بولے جاتے ہیں، اس لیے متلازم ہیں","متضاد":"کے معنی ایک دوسرے کے الٹ ہیں، اس لیے متضاد ہیں","مترادف":"کا مطلب ایک جیسا ہے، اس لیے مترادف ہیں"}
T3 = []
for i, (x, y, k) in enumerate(CL):
    T3.append(("U" if i < 6 else "A", "‘%s، %s’ کس قسم کی جوڑی ہے؟" % (x, y), k, *[z for z in KINDS if z != k],
        "‘%s’ اور ‘%s’ %s۔" % (x, y, WHY[k])))

DEF = [
("K","ایسے الفاظ جو عموماً ایک ساتھ بولے جاتے ہوں اور ایک کا ذکر دوسرے کی یاد دلائے، کہلاتے ہیں:","متلازم","متضاد","مترادف","مشتبہ","ساتھ ساتھ بولے جانے والے الفاظ کو متلازم کہتے ہیں۔"),
("K","‘متلازم’ کا لفظی مطلب ہے:","ایک دوسرے کے ساتھ لازم رہنے والے","ایک دوسرے کے الٹ","ایک جیسے معنی والے","الگ الگ رہنے والے","متلازم ‘لازم’ سے ہے، یعنی ایک دوسرے کے ساتھ لگے رہنے والے۔"),
]
def blank(s, a, d, pair): return ("A", s + "<br>خالی جگہ کے لیے مناسب متلازم لفظ منتخب کیجیے:", a, *d, "‘%s’ اور ‘%s’ متلازم ہیں، اس لیے خالی جگہ میں ‘%s’ آئے گا۔" % (pair[0], pair[1], a))
