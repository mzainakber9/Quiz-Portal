blank("مداری نے ڈھول اور ____ بجا کر مجمع اکٹھا کر لیا۔","تاشہ",["کمان","دھاگا","چاندی"],("ڈھول","تاشہ")),
blank("رات کو آسمان پر چاند اور ____ چمک رہے تھے۔","ستارے",["بیل","تیل","بلبل"],("چاند","ستارے")),
blank("درزی نے سوئی اور ____ سے قمیص سی دی۔","دھاگا",["دوات","کمان","ہانڈی"],("سوئی","دھاگا")),
blank("بچے چور اور ____ کا کھیل کھیل رہے تھے۔","سپاہی",["وزیر","پروانہ","دھوپ"],("چور","سپاہی")),
